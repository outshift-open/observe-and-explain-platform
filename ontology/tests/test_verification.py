"""Tests for oxp_ontology.verification (instance-level SHACL conformance checks).

Requires the ``verify`` extra (pyshacl) and the generated Pydantic models
(``models.nodes``) — regenerated by CI before this file runs, same as
test_models.py. Running `python scripts/generate_models.py` locally first is
required to run this file directly.
"""

import datetime

import pydantic
import pytest

from oxp_ontology.verification import (
    KGVerificationReport,
    OntologyValidationError,
    ShapeViolation,
    verify_kg_object,
)

pyshacl = pytest.importorskip("pyshacl")


def _consistency_report(*, with_group=True, **overrides):
    """Return (node, edges) -- ofSemanticGroup is a real KGEdge class, not a
    field on ConsistencyReport, so it can't be passed as a node kwarg (that's
    now a pydantic extra_forbidden error). Pass the edges to verify_kg_object
    separately; with_group=False omits it, to test the mandatory-property
    violation."""
    from oxp_ontology.models.edges.of_semantic_group import ofSemanticGroup
    from oxp_ontology.models.nodes.consistency_report import ConsistencyReport

    defaults = {
        "id": "consistency-1",
        # dataType deliberately not 'metric' here: aboutMetric then becomes
        # mandatory (AnalysisElementAboutMetricShape) and points at a
        # mas:Metric node, which a single-instance graph can't establish --
        # see TestConditionalAboutMetricRule below for the part of that rule
        # this validation path *can* exercise.
        "dataType": "text",
        "mean": 0.87,
        "confidenceInterval": '{"lower": 0.8, "upper": 0.9}',
        "confidenceIndicator": "high",
    }
    defaults.update(overrides)
    node = ConsistencyReport(**defaults)
    edges = (
        [ofSemanticGroup(source_id=node.id, target_id="grp_42")] if with_group else []
    )
    return node, edges


