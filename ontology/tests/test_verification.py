class TestValidObjectsConform:
    def test_consistency_report_conforms(self):
        node, edges = _consistency_report()
        report = verify_kg_object(node, edges=edges)

        assert isinstance(report, KGVerificationReport)
        assert report.conforms is True
        assert report.errors == []

